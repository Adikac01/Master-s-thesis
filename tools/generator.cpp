// Finds a maximal admissible set of symbols (chapter 3).
// usage: generator [output]
//        generator --count [limit]
//        generator --all [seconds] [threads]
#include "conditions.hpp"
#include "dna.hpp"
#include "report.hpp"
#include "search.hpp"

#include <algorithm>
#include <chrono>
#include <cmath>
#include <exception>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <string>
#include <thread>
#include <vector>

namespace {

const char* const DEFAULT_OUTPUT = "data/generated.txt";
const unsigned long long DEFAULT_LIMIT = 1000000;
const double DEFAULT_SECONDS = 300.0;
const double MAX_SECONDS = 1e6;
const unsigned MAX_DEFAULT_THREADS = 8;
const unsigned long long MAX_THREADS = 256;  // one per choice is already plenty

int usageError(const std::string& message) {
    std::cerr << "generator: " << message << "\n"
              << "usage: generator [output]\n"
              << "       generator --count [limit]\n"
              << "       generator --all [seconds] [threads]\n";
    return 2;
}

// The whole argument has to be a positive number, nothing else.
bool parsePositive(const std::string& text, unsigned long long& value) {
    if (text.empty() || text[0] == '-') return false;
    try {
        std::size_t used = 0;
        value = std::stoull(text, &used);
        return used == text.size() && value > 0;
    } catch (const std::exception&) {
        return false;
    }
}

bool parsePositive(const std::string& text, double& value) {
    try {
        std::size_t used = 0;
        value = std::stod(text, &used);
        return used == text.size() && std::isfinite(value) && value > 0;
    } catch (const std::exception&) {
        return false;
    }
}

double secondsSince(std::chrono::steady_clock::time_point start) {
    return std::chrono::duration<double>(std::chrono::steady_clock::now() - start)
        .count();
}

void writeSolution(const std::string& path, const conditions::SymbolList& symbols) {
    std::ofstream output(path);
    if (!output) {
        std::cerr << "Cannot write to " << path << "\n";
        return;
    }
    output << "# Generated by bin/generator.\n"
           << "# Column 1: strand 5'-3'. Column 2: complementary strand 3'-5'.\n\n";
    for (const dna::Word& symbol : symbols)
        output << symbol << "  " << dna::complement(symbol) << "\n";
}

int runFirst(const search::Problem& problem, const std::string& outputPath) {
    const auto started = std::chrono::steady_clock::now();
    conditions::SymbolList solution;
    unsigned usedChoice = 0;
    unsigned triedChoices = 0;

    for (unsigned choice = 0; choice < problem.choiceCount(); ++choice) {
        ++triedChoices;
        solution = search::firstCover(problem, choice);
        if (!solution.empty()) {
            usedChoice = choice;
            break;
        }
    }

    std::cout << "Choices tried: " << triedChoices << "\n"
              << "Elapsed: " << secondsSince(started) << " s\n\n";

    if (solution.empty()) {
        std::cout << "No admissible set found.\n";
        return 1;
    }

    std::cout << "Symbols found: " << solution.size() << "\nBanned sides:\n";
    for (std::size_t i = 0; i < problem.splits.size(); ++i) {
        const bool banPrefix = (usedChoice >> i) & 1u;
        std::cout << "  " << (banPrefix ? "prefix " : "suffix ")
                  << (banPrefix ? problem.splits[i].prefix : problem.splits[i].suffix)
                  << "\n";
    }
    std::cout << "\n";

    if (report::summary(conditions::verifyAll(solution)) != 0) return 1;

    writeSolution(outputPath, solution);
    std::cout << "\nWritten to " << outputPath << "\n";
    return 0;
}

int runCounting(const search::Problem& problem, std::size_t limit) {
    std::cout << "Counting solutions, stopping at " << limit << ".\n\n";

    for (unsigned choice = 0; choice < problem.choiceCount(); ++choice) {
        const auto started = std::chrono::steady_clock::now();
        const std::size_t found = search::countCovers(problem, choice, limit);
        if (found == 0) continue;

        const double seconds = secondsSince(started);
        std::cout << "First choice admitting a solution: " << choice << "\n"
                  << "Solutions found: " << found
                  << (found == limit ? " (limit reached, more remain)" : "") << "\n"
                  << "Elapsed: " << seconds << " s\n";
        if (seconds > 0.0)
            std::cout << "Rate: " << static_cast<std::size_t>(found / seconds)
                      << " solutions per second\n";
        std::cout << "\nNote: this counts sets admissible under one choice of\n"
                     "banned sides. Different choices overlap, so the counts\n"
                     "must not simply be added.\n";
        return 0;
    }
    std::cout << "No choice admits a solution.\n";
    return 1;
}

int runAll(const search::Problem& problem, double seconds, unsigned threads) {
    const auto started = std::chrono::steady_clock::now();
    std::cout << "Searching all " << problem.choiceCount() << " choices for about "
              << seconds << " s on " << threads
              << (threads == 1 ? " thread.\n\n" : " threads.\n\n");

    const std::vector<search::Outcome> outcomes = search::searchAll(
        problem, seconds, threads, [](int round, std::size_t open, double slice) {
            std::cout << "round " << round << ": " << open << " choices open, "
                      << slice << " s each" << std::endl;
        });

    std::cout << "\nchoice          covers   distinct sets   status\n";
    unsigned withCover = 0, provenEmpty = 0, undecided = 0, unfinished = 0;
    unsigned long long totalDistinct = 0;
    for (unsigned choice = 0; choice < outcomes.size(); ++choice) {
        const search::Outcome& outcome = outcomes[choice];
        if (outcome.covers > 0) ++withCover;
        else if (outcome.finished) ++provenEmpty;
        else ++undecided;
        if (!outcome.finished) ++unfinished;
        totalDistinct += outcome.distinct;
        if (outcome.covers > 0 || !outcome.finished)
            std::cout << std::setw(6) << choice << std::setw(16) << outcome.covers
                      << std::setw(16) << outcome.distinct << "   "
                      << (outcome.finished ? "complete" : "cut off") << "\n";
    }

    // The parity argument proves these empty without any search, so none of
    // them may have a cover; checking it guards both the theorem and the code.
    unsigned ruledOut = 0, ruledOutWithCover = 0;
    for (unsigned choice = 0; choice < outcomes.size(); ++choice)
        if (search::ruledOutByParity(problem, choice)) {
            ++ruledOut;
            if (outcomes[choice].covers > 0) ++ruledOutWithCover;
        }

    std::cout << "\nChoices with at least one cover:   " << withCover << "\n"
              << "Choices proven to admit no cover:  " << provenEmpty << "\n"
              << "Choices still undecided:           " << undecided << "\n"
              << "Ruled out by the parity argument:  " << ruledOut;
    if (ruledOutWithCover == 0)
        std::cout << " (none has a cover)\n";
    else
        std::cout << " (WARNING: " << ruledOutWithCover << " have a cover)\n";
    std::cout << "Distinct admissible sets found:    " << totalDistinct;
    if (unfinished == 0)
        std::cout << " (all of them)\n";
    else
        std::cout << " (a lower bound: " << unfinished << " choices were cut off)\n";
    std::cout << "Elapsed: " << secondsSince(started) << " s\n";
    return 0;
}

search::Problem setUp() {
    report::heading("Generating a maximal admissible set of symbols");
    search::Problem problem = search::makeProblem();
    std::cout << "Columns (rho-orbits): " << problem.columns.size() << "\n"
              << "Rows (candidates usable in some admissible set): " << problem.candidates.size()
              << "\n"
              << "Ways of satisfying (B2): " << problem.choiceCount() << "\n\n";
    return problem;
}

}  // namespace

int main(int argc, char* argv[]) {
    const std::vector<std::string> args(argv + 1, argv + argc);
    const std::string mode = args.empty() ? std::string() : args[0];

    if (mode == "--count") {
        if (args.size() > 2) return usageError("too many arguments");
        unsigned long long limit = DEFAULT_LIMIT;
        if (args.size() == 2 && !parsePositive(args[1], limit))
            return usageError("limit must be a positive integer");
        return runCounting(setUp(), limit);
    }
    if (mode == "--all") {
        if (args.size() > 3) return usageError("too many arguments");
        double seconds = DEFAULT_SECONDS;
        if (args.size() >= 2 && (!parsePositive(args[1], seconds) || seconds > MAX_SECONDS))
            return usageError("seconds must be a positive number up to 1000000");
        unsigned long long threads =
            std::min(MAX_DEFAULT_THREADS, std::max(1u, std::thread::hardware_concurrency()));
        if (args.size() == 3 && (!parsePositive(args[2], threads) || threads > MAX_THREADS))
            return usageError("threads must be an integer from 1 to 256");
        return runAll(setUp(), seconds, static_cast<unsigned>(threads));
    }
    if (mode.rfind("--", 0) == 0) return usageError("unknown option '" + mode + "'");
    if (args.size() > 1) return usageError("too many arguments");
    return runFirst(setUp(), args.empty() ? DEFAULT_OUTPUT : mode);
}
